package io.github.crystals_of_the_soul.entity;

public class Enemy {

    private float x;
    private float y;

    public Enemy(float x, float y) {
        this.x = x;
        this.y = y;
    }

    public float getX() {
        return x;
    }

    public float getY() {
        return y;
    }
}
